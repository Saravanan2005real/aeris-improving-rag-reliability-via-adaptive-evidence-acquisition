import json
import re
from typing import List, Optional

import ollama
from pydantic import BaseModel, Field

from app.config import settings
from app.planning.schemas import InformationRequirement


class EvidenceItem(BaseModel):
    chunk_id: str
    document_id: str
    text: str
    language: str
    pages: List[int] = Field(default_factory=list)
    start_page: int
    end_page: int

    # Retrieval/reranking score if available.
    retrieval_score: Optional[float] = None
    rerank_score: Optional[float] = None


class RequirementCoverage(BaseModel):
    requirement_id: str

    coverage_status: str

    coverage_score: float = Field(
        ge=0.0,
        le=1.0
    )

    directness: float = Field(
        ge=0.0,
        le=1.0
    )

    relevance: float = Field(
        ge=0.0,
        le=1.0
    )

    completeness: float = Field(
        ge=0.0,
        le=1.0
    )

    evidence_type_match: float = Field(
        ge=0.0,
        le=1.0
    )

    supporting_chunk_ids: List[str] = Field(
        default_factory=list
    )

    evidence_count: int = 0

    best_evidence_score: float = 0.0

    explanation: str


class EvidenceCoverageResult(BaseModel):
    question: str

    requirement_coverages: List[RequirementCoverage]

    overall_coverage: float = Field(
        ge=0.0,
        le=1.0
    )

    covered_requirements: List[str] = Field(
        default_factory=list
    )

    partial_requirements: List[str] = Field(
        default_factory=list
    )

    missing_requirements: List[str] = Field(
        default_factory=list
    )


class EvidenceCoverageEstimator:
    """
    Estimates whether retrieved evidence satisfies the information
    requirements generated by AERIS-RAG Step 8.
    """

    def __init__(
        self,
        model: Optional[str] = None,
        host: Optional[str] = None,
    ):
        self.model = model or settings.ollama_model
        self.host = host or settings.ollama_host

        self.client = ollama.Client(host=self.host)

    def _build_prompt(
        self,
        requirement: InformationRequirement,
        evidence: EvidenceItem,
    ) -> str:

        return f"""
You are a strict evidence verifier for AERIS-RAG.
Evaluate whether the DOCUMENT EVIDENCE supports the INFORMATION REQUIREMENT.

REQUIREMENT:
{requirement.description}
(Type: {requirement.requirement_type}, Expected Evidence: {requirement.expected_evidence_type})
Entities: {", ".join(requirement.entities)}

EVIDENCE:
{evidence.text}

RULES:
- Score 4 dimensions (0.0 to 1.0):
  1. directness: Does the evidence explicitly address the requirement?
  2. relevance: Is it actually relevant to the requirement?
  3. completeness: Is there enough info to satisfy the requirement?
  4. evidence_type_match: Does it contain the expected evidence type?
- coverage_score = (0.30 * directness) + (0.25 * relevance) + (0.25 * completeness) + (0.20 * evidence_type_match)
- coverage_status: "SUPPORTED" if score >= 0.70, "PARTIAL" if score >= 0.35, else "UNSUPPORTED"
- Do not infer facts. Related topic/terminology is NOT supporting evidence.
- Respond ONLY with valid JSON.

OUTPUT FORMAT:
{{
  "directness": 0.0,
  "relevance": 0.0,
  "completeness": 0.0,
  "evidence_type_match": 0.0,
  "coverage_status": "SUPPORTED|PARTIAL|UNSUPPORTED",
  "coverage_score": 0.0,
  "explanation": "brief explanation"
}}
""".strip()

    @staticmethod
    def _extract_json(text: str) -> str:
        text = text.strip()

        text = re.sub(
            r"^```(?:json)?\s*",
            "",
            text
        )

        text = re.sub(
            r"\s*```$",
            "",
            text
        )

        start = text.find("{")
        end = text.rfind("}")

        if start == -1 or end == -1 or end <= start:
            raise ValueError(
                "No valid JSON object found in model response."
            )

        return text[start:end + 1]

    def _evaluate_pair(
        self,
        requirement: InformationRequirement,
        evidence: EvidenceItem,
    ) -> dict:

        prompt = self._build_prompt(
            requirement,
            evidence,
        )

        response = self.client.chat(
            model=self.model,
            messages=[
                {
                    "role": "user",
                    "content": prompt,
                }
            ],
            options={
                "temperature": 0,
            },
        )

        raw_content = response["message"]["content"]

        json_text = self._extract_json(
            raw_content
        )

        data = json.loads(
            json_text
        )

        required_fields = [
            "directness",
            "relevance",
            "completeness",
            "evidence_type_match",
            "coverage_status",
            "coverage_score",
            "explanation",
        ]

        for field in required_fields:

            if field not in data:
                raise ValueError(
                    f"Missing field: {field}"
                )

        status = str(
            data["coverage_status"]
        ).upper()

        if status not in {
            "SUPPORTED",
            "PARTIAL",
            "UNSUPPORTED",
        }:
            raise ValueError(
                f"Invalid coverage status: {status}"
            )

        directness = float(
            data["directness"]
        )

        relevance = float(
            data["relevance"]
        )

        completeness = float(
            data["completeness"]
        )

        evidence_type_match = float(
            data["evidence_type_match"]
        )

        directness = max(
            0.0,
            min(1.0, directness)
        )

        relevance = max(
            0.0,
            min(1.0, relevance)
        )

        completeness = max(
            0.0,
            min(1.0, completeness)
        )

        evidence_type_match = max(
            0.0,
            min(1.0, evidence_type_match)
        )

        # Calculate the score ourselves.
        # Do not trust the LLM's arithmetic.
        coverage_score = (
            0.30 * directness
            + 0.25 * relevance
            + 0.25 * completeness
            + 0.20 * evidence_type_match
        )

        # Enforce status from the calculated score.
        if coverage_score >= 0.70:
            status = "SUPPORTED"

        elif coverage_score >= 0.35:
            status = "PARTIAL"

        else:
            status = "UNSUPPORTED"

        return {
            "status": status,
            "score": coverage_score,
            "directness": directness,
            "relevance": relevance,
            "completeness": completeness,
            "evidence_type_match": evidence_type_match,
            "explanation": str(
                data["explanation"]
            ).strip(),
        }

    def estimate(
        self,
        question: str,
        requirements: List[InformationRequirement],
        requirement_evidence: dict[str, List[EvidenceItem]],
    ) -> EvidenceCoverageResult:

        if not question or not question.strip():
            raise ValueError(
                "question cannot be empty"
            )

        if not requirements:
            raise ValueError(
                "requirements cannot be empty"
            )

        if not requirement_evidence:
            raise ValueError(
                "requirement_evidence cannot be empty"
            )

        requirement_coverages = []

        for requirement in requirements:

            evidence_evaluations = []

            req_evidence = requirement_evidence.get(requirement.requirement_id, [])

            for item in req_evidence:

                try:
                    evaluation = self._evaluate_pair(
                        requirement,
                        item,
                    )

                    evidence_evaluations.append(
                        {
                            "evidence": item,
                            **evaluation,
                        }
                    )

                    # Early stopping:
                    # If the strongest available evidence already
                    # satisfies the requirement, do not spend additional
                    # Ollama calls evaluating weaker evidence.
                    if (
                        evaluation["status"] == "SUPPORTED"
                        and evaluation["score"] >= 0.70
                    ):
                        break

                except Exception as exc:
                    print(
                        f"[Coverage] Evaluation failed for "
                        f"requirement={requirement.requirement_id}, "
                        f"chunk={item.chunk_id}: {exc}"
                    )
                    continue

            if not evidence_evaluations:
                requirement_coverages.append(
                    RequirementCoverage(
                        requirement_id=requirement.requirement_id,
                        coverage_status="UNSUPPORTED",
                        coverage_score=0.0,
                        directness=0.0,
                        relevance=0.0,
                        completeness=0.0,
                        evidence_type_match=0.0,
                        supporting_chunk_ids=[],
                        evidence_count=0,
                        best_evidence_score=0.0,
                        explanation=(
                            "No evidence could be successfully evaluated."
                        ),
                    )
                )

                continue

            evidence_evaluations.sort(
                key=lambda x: x["score"],
                reverse=True,
            )

            best = evidence_evaluations[0]

            supporting = [
                evaluation
                for evaluation in evidence_evaluations
                if evaluation["status"]
                in {
                    "SUPPORTED",
                    "PARTIAL",
                }
                and evaluation["score"] >= 0.35
            ]

            supporting.sort(
                key=lambda x: x["score"],
                reverse=True,
            )

            # Keep only the strongest evidence.
            supporting = supporting[:5]

            supporting_chunk_ids = [
                item["evidence"].chunk_id
                for item in supporting
            ]

            best_score = float(
                best["score"]
            )

            final_status = best["status"]

            requirement_coverages.append(
                RequirementCoverage(
                    requirement_id=requirement.requirement_id,
                    coverage_status=final_status,
                    coverage_score=best_score,
                    directness=float(
                        best["directness"]
                    ),
                    relevance=float(
                        best["relevance"]
                    ),
                    completeness=float(
                        best["completeness"]
                    ),
                    evidence_type_match=float(
                        best["evidence_type_match"]
                    ),
                    supporting_chunk_ids=supporting_chunk_ids,
                    evidence_count=len(
                        supporting_chunk_ids
                    ),
                    best_evidence_score=best_score,
                    explanation=best["explanation"],
                )
            )

        if requirement_coverages:

            overall_coverage = sum(
                coverage.coverage_score
                for coverage in requirement_coverages
            ) / len(requirement_coverages)

        else:
            overall_coverage = 0.0

        covered_requirements = [
            coverage.requirement_id
            for coverage in requirement_coverages
            if coverage.coverage_status == "SUPPORTED"
        ]

        partial_requirements = [
            coverage.requirement_id
            for coverage in requirement_coverages
            if coverage.coverage_status == "PARTIAL"
        ]

        missing_requirements = [
            coverage.requirement_id
            for coverage in requirement_coverages
            if coverage.coverage_status == "UNSUPPORTED"
        ]

        return EvidenceCoverageResult(
            question=question,
            requirement_coverages=requirement_coverages,
            overall_coverage=overall_coverage,
            covered_requirements=covered_requirements,
            partial_requirements=partial_requirements,
            missing_requirements=missing_requirements,
        )
